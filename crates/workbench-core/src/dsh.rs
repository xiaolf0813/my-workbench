        std::fs::create_dir_all(home.join("profiles").join("node_modules").join("pkg")).unwrap();
        std::fs::write(home.join("profiles").join("loose"), "").unwrap();
        assert_eq!(
            profile_names(&find_profile_dirs(&home, None)),
            vec!["alpha", "beta", "gamma"]
        );
