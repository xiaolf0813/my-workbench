    "# >>> my-workbench lane settings page (managed block - regenerated by `my-workbench --dsh`) >>>";
pub const LANE_UI_BLOCK_END: &str = "# <<< my-workbench lane settings page <<<";

/// `{{dep:<alias>}}` placeholders in the lane plugin's host module — each
/// names a deployment package the plugin imports at runtime and is replaced
/// with an absolute `file:` URL at install time.
pub fn dep_re() -> &'static regex::Regex {
    static DEP_RE: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
    DEP_RE.get_or_init(|| regex::Regex::new(r"\{\{dep:([\w-]+)\}\}").expect("valid DEP_RE"))
}

/// Deployment packages the lane plugin imports, keyed by template alias
/// (`DSH_LANE_PLUGIN_DEPS` in the CLI; exposed so the engine can pass the dep
/// map to [`dsh_deps::resolve_lane_dependencies`]).
pub const DSH_LANE_PLUGIN_DEPS: [(&str, &str); 2] = [
    ("dsh-tools", "@deepseek-ai/dsh-tools"),
    ("schemastery", "@deepseek-ai/schemastery"),
];

/// The dep map in [`DSH_LANE_PLUGIN_DEPS`], as consumed by the resolve fns.
pub fn lane_plugin_dep_map() -> BTreeMap<String, String> {
    DSH_LANE_PLUGIN_DEPS
        .iter()
        .map(|(alias, package)| (alias.to_string(), package.to_string()))
        .collect()
}

/// The preset root inside a DSH home.
pub fn preset_root(home: &Path) -> PathBuf {
    home.join(".agent-presets").join(DSH_PRESET_ID)
}

/// Never copied, no matter where they appear in a source tree (`isSkipped`).
/// Applies to any directory walk over DSH source material; the preset's fixed
/// file set never contains such a name.
pub fn is_skipped(name: &str) -> bool {
    name == "node_modules"
        || name == "package-lock.json"
        || name == "settings.local.json"
        || name.starts_with('.')
}

