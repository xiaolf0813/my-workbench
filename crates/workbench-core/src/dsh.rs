// ---------------------------------------------------------------- display

/// True when the DSH home sits inside the user home, so destinations display
/// as `~/…` (the CLI's `userLevel` display decision).
fn home_is_user_level(home: &Path, user_home: &Path) -> bool {
    home.starts_with(user_home)
}

/// Display path: `~/…` relative to the user home for a user-level DSH home,
/// the absolute path otherwise.
fn display_path(path: &Path, user_home: &Path, user_level: bool) -> String {
    if user_level {
        if let Ok(relative) = path.strip_prefix(user_home) {
            return format!("~/{}", relative.to_string_lossy().replace('\\', "/"));
        }
    }
    path.to_string_lossy().into_owned()
}

fn log(sink: &dyn EventSink, level: LogLevel, text: impl Into<String>) {
    let time_ms = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|since| since.as_millis() as u64)
        .unwrap_or(0);
    sink.emit(InstallEvent::Log {
        time_ms,
        target: Some(Target::Dsh),
        level,
        text: text.into(),
    });
}

// ----------------------------------------------------------------------- plan

/// DSH plan: zero writes; per-file Create/Skip/Overwrite items under the
/// preset root plus one `ManagedBlock` item per profile whose patch row would
/// be added or updated (an unchanged or skipped row becomes notes). Dependency
/// resolution happened upstream — `resolved_deps` is the alias → `file:` URL
/// map [`dsh_deps::resolve_lane_dependencies`] produced.
pub fn plan_dsh(
    source_root: &Path,
    ctx: &EngineContext,
    sel: &Selection,
    resolved_deps: &BTreeMap<String, String>,
) -> Result<ModuleOutcome, WorkbenchError> {
    let home = dsh_home(&ctx.home);
    plan_dsh_in(source_root, sel, resolved_deps, &home)
}

/// Parameter-injected variant of [`plan_dsh`] (the DSH home supplied by the
/// caller instead of `$DSH_HOME`).
pub fn plan_dsh_in(
    source_root: &Path,
    sel: &Selection,
    resolved_deps: &BTreeMap<String, String>,
    home: &Path,
) -> Result<ModuleOutcome, WorkbenchError> {
    let lanes = lanes(source_root)?;
    let outputs = dsh_outputs(source_root, &lanes, resolved_deps)?;
    let preset = preset_root(home);

    let mut outcome = ModuleOutcome::default();
    for output in &outputs {
        let dest = preset.join(output.dest_rel());
        let exists = dest.exists();
        // writeAgent's gate: `exists && !force && !regenerate` skips. A
        // regenerate entry is therefore NEVER a skip — it is written on every
        // run; force only decides whether the plain entries may overwrite.
        let kind = if exists && (sel.force || output.regenerates()) {
            PlanKind::Overwrite
        } else if exists {
            PlanKind::Skip
        } else {
            PlanKind::Create
        };
        match kind {
            PlanKind::Create => outcome.created += 1,
            PlanKind::Skip => outcome.skipped += 1,
            PlanKind::Overwrite => outcome.overwritten += 1,
            PlanKind::ManagedBlock => unreachable!("file items are never ManagedBlock"),
        }
        outcome.items.push(PlanItem {
            target: Target::Dsh,
            path: dest,
            source_rel: output.source_rel().to_owned(),
            kind,
        });
    }

    let row_name = lane_ui_row_name(&preset);
    let profiles = find_profile_dirs(home, sel.dsh_profile.as_deref());
    if profiles.is_empty() {
        outcome.notes.extend(no_profile_notes(home, sel.dsh_profile.as_deref()));
        outcome.notes.push(manual_row_note(
            &format!("你的 profile 的 {PROFILE_PATCH_FILENAME}"),
            &row_name,
        ));
    } else {
        for profile in &profiles {
            let (result, _) = compute_lane_ui_patch_row(&profile.dir, &row_name)?;
            match result {
                PatchOutcome::Unchanged => {
                    outcome
                        .notes
                        .push(format!("{} 的受管块已是最新，无需更改", profile.name));
                }
                PatchOutcome::Skipped => {
                    outcome.notes.push(format!(
                        "{} 不是纯补丁列表，受管行未写入（直接追加会破坏该文件）",
                        profile.dir.join(PROFILE_PATCH_FILENAME).display()
                    ));
                    outcome
                        .notes
                        .push(manual_row_note("该文件", &row_name));
                }
                PatchOutcome::Added | PatchOutcome::Updated => {
                    outcome.managed_blocks += 1;
                    outcome.items.push(PlanItem {
                        target: Target::Dsh,
                        path: profile.dir.join(PROFILE_PATCH_FILENAME),
                        source_rel: profile_source_rel(home, &profile.dir),
                        kind: PlanKind::ManagedBlock,
                    });
                }
            }
        }
    }
    outcome
        .notes
        .push("DSH 在会话启动时读取预设：请打开新会话并选择该预设".to_owned());
    Ok(outcome)
}

/// The notes for a run that found no profile to mount (`applyDsh`'s empty-set
/// branch): why nothing was written, plus the entries actually present when
/// that helps name one.
fn no_profile_notes(home: &Path, dsh_profile: Option<&str>) -> Vec<String> {
    let profiles_dir = home.join("profiles");
    let mut notes = Vec::new();
    match dsh_profile {
        Some(name) => notes.push(format!(
            "--dsh-profile {name} 未命中 {} 下的任何目录，设置页未写入",
            profiles_dir.display()
        )),
        None => {
            notes.push(format!(
                "未在 {} 下找到可用 profile 目录，设置页未写入",
                profiles_dir.display()
            ));
            let present = sorted_readdir(&profiles_dir)
                .into_iter()
                .filter(|name| name != PROFILE_LINK_DIR)
                .collect::<Vec<_>>()
                .join(", ");
            notes.push(if present.is_empty() {
                "请先启动一次 DSH 以创建 profile 目录，然后重新运行 --dsh".to_owned()
            } else {
                format!("现有条目：{present}；没有可用 profile，请用 --dsh-profile <name> 显式指定")
            });
        }
    }
    notes
}

/// The manual-row instructions for a profile the target could not mount
/// (`applyDsh`'s skip notes, collapsed into one note).
fn manual_row_note(where_phrase: &str, row_name: &str) -> String {
    format!(
        "请在 {where_phrase} 中手动加入以下行以启用该页面：\n  - insert:\n      - id: \
         my-workbench-lanes-ui\n        name: '{row_name}'"
    )
}

fn profile_source_rel(home: &Path, profile_dir: &Path) -> String {
    let fallback = profile_dir
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_default();
    let relative = profile_dir
        .strip_prefix(home)
        .map(|relative| relative.to_string_lossy().replace('\\', "/"))
        .unwrap_or(fallback);
    format!("{relative}/{PROFILE_PATCH_FILENAME}")
}

// ------------------------------------------------------------------- execute

/// DSH execute: resolves the plugin's two deployment imports BEFORE the first
/// write (a DSH home that cannot supply them fails with nothing
/// half-installed), then writes the preset file set with log events and
/// cooperative cancellation between files, and finally maintains the managed
/// row in every profile found (or the one named by `--dsh-profile`).
pub fn execute_dsh(
    source_root: &Path,
    ctx: &EngineContext,
    sel: &Selection,
    sink: &dyn EventSink,
) -> Result<ModuleOutcome, WorkbenchError> {
    let home = dsh_home(&ctx.home);
    let path_env = std::env::var("PATH").unwrap_or_default();
    let env_modules = std::env::var("MY_WORKBENCH_DSH_NODE_MODULES")
        .ok()
        .filter(|value| !value.is_empty());
    execute_dsh_in(
        source_root,
        ctx,
        sel,
        sink,
        &home,
        &path_env,
        env_modules.as_deref().map(Path::new),
    )
}

/// Parameter-injected variant of [`execute_dsh`] (home / `PATH` /
/// `MY_WORKBENCH_DSH_NODE_MODULES` supplied by the caller).
pub fn execute_dsh_in(
    source_root: &Path,
    ctx: &EngineContext,
    sel: &Selection,
    sink: &dyn EventSink,
    home: &Path,
    path_env: &str,
    env_modules: Option<&Path>,
) -> Result<ModuleOutcome, WorkbenchError> {
    // Resolve the plugin's two deployment imports BEFORE the first write: a DSH
    // home that cannot supply them must fail with nothing half-installed.
    let specifiers = dsh_deps::resolve_lane_dependencies_in(
        home,
        &lane_plugin_dep_map(),
        path_env,
        env_modules,
    )?;
    let lanes = lanes(source_root)?;
    let outputs = dsh_outputs(source_root, &lanes, &specifiers)?;
    let preset = preset_root(home);
    let user_level = home_is_user_level(home, &ctx.home);

    let shown = display_path(&preset, &ctx.home, user_level);
    log(
        sink,
        LogLevel::Info,
        format!("{shown}/（用户级：preset.yml、agent.cordis.yml、lane-plugin/、lane-plugin-ui/）"),
    );

    let mut outcome = ModuleOutcome::default();
    for output in &outputs {
        if sink.is_cancelled() {
            return Ok(outcome);
        }
        let dest_rel = output.dest_rel();
        if dest_rel == "lane-plugin/package.json" {
            log(
                sink,
                LogLevel::Info,
                format!("{DSH_LANE_PLUGIN_DIR}/（宿主插件与 {} 个专项提示词）", lanes.len()),
            );
        } else if dest_rel == "lane-plugin-ui/package.json" {
            log(
                sink,
                LogLevel::Info,
                format!("{DSH_LANE_UI_DIR}/（设置页）"),
            );
        }
        let dest = preset.join(dest_rel);
        let shown = display_path(&dest, &ctx.home, user_level);
        let exists = dest.exists();
        // writeAgent's gate, verbatim: `exists && !force && !regenerate` skips.
        // The three release-stamped artifacts regenerate unconditionally.
        if exists && !sel.force && !output.regenerates() {
            outcome.skipped += 1;
            log(sink, LogLevel::Info, format!("跳过 {shown}（已存在）"));
            continue;
        }
        match output {
            DshOutput::Copy { from, .. } => {
                std::fs::create_dir_all(dest.parent().expect("dest has a parent"))?;
                std::fs::copy(from, &dest)?;
            }
            DshOutput::Rendered { text, .. } => {
                std::fs::create_dir_all(dest.parent().expect("dest has a parent"))?;
                std::fs::write(&dest, text)?;
            }
        }
        if exists {
            outcome.overwritten += 1;
        } else {
            outcome.created += 1;
        }
        let refresh = if output.regenerates() && exists && !sel.force {
            "（已刷新：由本发行版渲染）"
        } else {
            ""
        };
        log(
            sink,
            LogLevel::Info,
            format!("{} {shown}{refresh}", if exists { "覆盖" } else { "新建" }),
        );
    }

    if sink.is_cancelled() {
        return Ok(outcome);
    }

    // The settings page is a CLIENT plugin, and dsh-client-modules only scans
    // the profile loader's own entries — a row inside an agent preset is never
    // seen. One row per profile is therefore the minimum footprint, and it is
    // the whole of it.
    let row_name = lane_ui_row_name(&preset);
    let profiles = find_profile_dirs(home, sel.dsh_profile.as_deref());
    if profiles.is_empty() {
        for note in no_profile_notes(home, sel.dsh_profile.as_deref()) {
            log(sink, LogLevel::Info, note);
        }
        log(
            sink,
            LogLevel::Info,
            manual_row_note(
                &format!("你的 profile 的 {PROFILE_PATCH_FILENAME}"),
                &row_name,
            ),
        );
    } else {
        for profile in &profiles {
            if sink.is_cancelled() {
                return Ok(outcome);
            }
            let patch_file = profile.dir.join(PROFILE_PATCH_FILENAME);
            let patch_existed = patch_file.exists();
            let shown = display_path(&patch_file, &ctx.home, user_level);
            // A profile chosen by the fallback or by name is not the profile
            // the user is looking at, so which one it is belongs in the line.
            let scope = match profile.source {
                ProfileSource::Profile => "",
                ProfileSource::Only => "（由 --dsh-profile 指定）",
                ProfileSource::Single => "（唯一 profile 目录）",
            };
            match write_lane_ui_patch_row(&profile.dir, &row_name)? {
                PatchOutcome::Skipped => {
                    log(
                        sink,
                        LogLevel::Warn,
                        format!(
                            "警告：{shown} 不是纯补丁列表，受管行未写入（直接追加会破坏该文件）"
                        ),
                    );
                    log(sink, LogLevel::Info, manual_row_note("该文件", &row_name));
                }
                PatchOutcome::Unchanged => {
                    log(
                        sink,
                        LogLevel::Info,
                        format!("跳过 {shown}{scope}（已是最新）"),
                    );
                    log(
                        sink,
                        LogLevel::Info,
                        "仅写入一条静态 UI 行；不安装任何工具或软件包",
                    );
                    log(
                        sink,
                        LogLevel::Info,
                        "受管块已是最新，无需更改",
                    );
                }
                PatchOutcome::Added => {
                    outcome.managed_blocks += 1;
                    let label = if patch_existed { "追加" } else { "新建" };
                    log(sink, LogLevel::Info, format!("{label} {shown}{scope}"));
                    log(
                        sink,
                        LogLevel::Info,
                        "仅写入一条静态 UI 行；不安装任何工具或软件包",
                    );
                }
                PatchOutcome::Updated => {
                    outcome.managed_blocks += 1;
                    log(sink, LogLevel::Info, format!("覆盖 {shown}{scope}"));
                    log(
                        sink,
                        LogLevel::Info,
                        "仅写入一条静态 UI 行；不安装任何工具或软件包",
                    );
                }
            }
        }
    }
    log(
        sink,
        LogLevel::Info,
        "DSH 在会话启动时读取预设：请打开新会话并选择该预设",
    );
    Ok(outcome)
}

// --------------------------------------------------------------------- drift

/// Stable display marker for the managed profile row's drift entry. The patch
/// layer is user-owned and copied from nowhere, so [`DriftFile::source_rel`]
/// has no source-relative origin to name and types.rs has no better field; a
/// fixed marker keeps the GUI display stable across profile names.
const MANAGED_PATCH_DRIFT_REL: &str = "cordis.patch.yml (managed block)";

/// Byte-compare what a DSH install WOULD write against what is on disk: the
/// nine preset files through the same render/copy set [`plan_dsh_in`] and
/// [`execute_dsh_in`] install, plus the managed row of every profile found
/// (drift reports on the full set — it has no `--dsh-profile` to narrow by).
/// See [`drift_dsh_with_compared`] for the exact semantics.
pub fn drift_dsh(
    source_root: &Path,
    home: &Path,
    force: bool,
) -> Result<Vec<DriftFile>, WorkbenchError> {
    drift_dsh_with_compared(source_root, home, force).map(|(drifted, _)| drifted)
}

/// [`drift_dsh`] plus the number of files the comparison examined, so the
/// engine can count DSH into `Tier1Report.compared` without knowing the
/// preset file set itself.
///
/// Semantics (`assemble --check` drift applied to an installed preset): a
/// preset file that exists on disk is compared byte-for-byte against
/// [`DshOutput::content_bytes`] and reported when it differs; one that is not
/// installed is not compared. Each profile's managed row is compared through
/// [`compute_lane_ui_patch_row`]: an unchanged block is not drift, a shape the
/// install refuses to touch writes nothing and therefore is not drift either,
/// and a block the install would add or rewrite is ONE drift entry attributed
/// to that profile's patch file — even when the patch file does not exist yet,
/// since the row is the install's only profile-layer footprint and its absence
/// is exactly what a rerun repairs. `force` is accepted but deliberately
/// ignored: drift is a content difference regardless of the overwrite flag.
pub fn drift_dsh_with_compared(
    source_root: &Path,
    home: &Path,
    force: bool,
) -> Result<(Vec<DriftFile>, usize), WorkbenchError> {
    let _ = force; // drift detection is force-independent (see doc above)
    let lanes = lanes(source_root)?;
    let resolved = dsh_deps::resolve_lane_dependencies(home, &lane_plugin_dep_map())?;
    let outputs = dsh_outputs(source_root, &lanes, &resolved)?;
    let preset = preset_root(home);

    let mut drifted = Vec::new();
    let mut compared = 0usize;
    for output in &outputs {
        let dest = preset.join(output.dest_rel());
        let Ok(on_disk) = std::fs::read(&dest) else {
            continue; // not installed → nothing to compare
        };
        compared += 1;
        if on_disk != output.content_bytes()? {
            drifted.push(DriftFile {
                path: dest,
                source_rel: output.source_rel().to_owned(),
                target: Target::Dsh,
            });
        }
    }

    for profile in &find_profile_dirs(home, None) {
        let row_name = lane_ui_row_name(&preset);
        let (outcome, _) = compute_lane_ui_patch_row(&profile.dir, &row_name)?;
        compared += 1;
        if matches!(outcome, PatchOutcome::Added | PatchOutcome::Updated) {
            drifted.push(DriftFile {
                path: profile.dir.join(PROFILE_PATCH_FILENAME),
                source_rel: MANAGED_PATCH_DRIFT_REL.to_owned(),
                target: Target::Dsh,
            });
        }
    }
    Ok((drifted, compared))
}

