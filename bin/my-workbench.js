/** The lane plugin's host module template, unmodified. */
function laneHostTemplate() {
  return readFileSync(join(DSH_LANE_PLUGIN_SRC, "host-package", "src", "index.js"), "utf8");
}

/**
 * Fill {{dep:<alias>}} in the lane plugin's host module. `specifiers` maps each
 * alias to the specifier to import: install passes absolute file: URLs to the
 * deployment's own copies, check passes the bare package names the plugin's
 * peerDependencies declare. Every declared alias must be consumed, so a typo in
 * either file fails here instead of at DSH session start.
 */
function renderLaneHost(specifiers) {
  const used = new Set();
  const rendered = laneHostTemplate().replace(DEP_RE, (raw, alias) => {
    const specifier = specifiers[alias];
    if (specifier === undefined) {
      throw new Error(
        `unknown dependency alias '${raw}' in the lane plugin host module (known: ${Object.keys(DSH_LANE_PLUGIN_DEPS).join(", ")})`,
      );
    }
    used.add(alias);
    return specifier;
  });
  for (const alias of Object.keys(DSH_LANE_PLUGIN_DEPS)) {
    if (!used.has(alias)) {
      throw new Error(`the lane plugin host module never imports '${alias}'; expected a '{{dep:${alias}}}' placeholder`);
    }
  }
  const leftover = rendered.match(/\{\{[\w-]+:[\w@/.-]+\}\}/);
  if (leftover) throw new Error(`the lane plugin host module left '${leftover[0]}' unfilled`);
  return rendered;
}

