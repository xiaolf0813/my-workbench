function activeCodexAgentsFile(root, opts, counts) {
  const fallback = join(root, "AGENTS.md");
  const override = join(root, "AGENTS.override.md");
  if (!existsSync(override)) return fallback;
  const text = readFileSync(override, "utf8");
  if (!text.trim()) return fallback;

  // Older installs could make an empty override active by adding only our block.
  const trimmed = text.trim();
  if (trimmed.startsWith(CODEX_AGENTS_BLOCK_BEGIN) && trimmed.endsWith(CODEX_AGENTS_BLOCK_END)
      && trimmed.indexOf(CODEX_AGENTS_BLOCK_BEGIN, 1) === -1
      && trimmed.indexOf(CODEX_AGENTS_BLOCK_END) === trimmed.length - CODEX_AGENTS_BLOCK_END.length) {
    if (!opts.dryRun) writeFileSync(override, text.replace(trimmed, ""));
    counts.overwritten++;
    console.log(`  restore    ${override}  (empty user override)${opts.dryRun ? "  (dry-run)" : ""}`);
    return fallback;
  }
  return override;
}

function writeCodexAgentsBlock(root, display, opts, counts) {
  const file = activeCodexAgentsFile(root, opts, counts);
  const existing = existsSync(file) ? readFileSync(file, "utf8") : null;
  const block = codexAgentsBlock(root);
  const begin = existing?.indexOf(CODEX_AGENTS_BLOCK_BEGIN) ?? -1;
  const strayEnd = existing?.indexOf(CODEX_AGENTS_BLOCK_END) ?? -1;
  let next;

  if (begin !== -1) {
    if (strayEnd !== -1 && strayEnd < begin) {
      throw new Error(`${file} has the managed block's closing marker before its opening marker; fix or delete the markers, then re-run`);
    }
    if (existing.indexOf(CODEX_AGENTS_BLOCK_BEGIN, begin + CODEX_AGENTS_BLOCK_BEGIN.length) !== -1) {
      throw new Error(`${file} contains more than one managed block opening marker; keep one block, then re-run`);
    }
    const end = existing.indexOf(CODEX_AGENTS_BLOCK_END, begin);
    if (end === -1) {
      throw new Error(`${file} has the managed block's opening marker but not its closing marker; fix or delete the block, then re-run`);
    }
    if (existing.indexOf(CODEX_AGENTS_BLOCK_END, end + CODEX_AGENTS_BLOCK_END.length) !== -1) {
      throw new Error(`${file} contains more than one managed block closing marker; keep one block, then re-run`);
    }
    next = existing.slice(0, begin) + block + existing.slice(end + CODEX_AGENTS_BLOCK_END.length);
  } else if (strayEnd !== -1) {
    throw new Error(`${file} has the managed block's closing marker but not its opening marker; fix or delete the marker, then re-run`);
  } else if (existing === null || existing === "") {
    next = `${block}\n`;
  } else {
    const separator = existing.endsWith("\n\n") ? "" : existing.endsWith("\n") ? "\n" : "\n\n";
    next = `${existing}${separator}${block}\n`;
  }

  const rel = display.displayPrefix + relative(display.displayRoot, file);
  if (next === existing) {
    counts.skipped++;
    console.log(`  skip       ${rel}  (managed block is current)`);
    return;
  }
  if (!opts.dryRun) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, next);
  }
  counts[existing === null ? "created" : "overwritten"]++;
  console.log(`  ${existing === null ? "create   " : "overwrite"}  ${rel}  (managed block)${opts.dryRun ? "  (dry-run)" : ""}`);
}

