function parseArgs(argv) {
  if (argv[0] === "assemble") {
    const rest = argv.slice(1);
    for (const arg of rest) {
      if (arg !== "--check" && arg !== "--force" && arg !== "--dry-run") {
        throw new Error(`unknown argument for assemble: ${arg}\n\n${HELP}`);
      }
    }
    return { command: "assemble", check: rest.includes("--check") };
  }

  const targets = new Set();
  let force = false;
  let dryRun = false;
  let user = false;
  let upgrade = false;
  let dshProfile;

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    switch (arg) {
      case "--opencode":
      case "opencode":
        targets.add("opencode");
        break;
      case "--omos":
      case "omos":
        targets.add("omos");
        break;
      case "--claude":
      case "claude":
        targets.add("claude");
        break;
      case "--zcode":
      case "zcode":
        targets.add("zcode");
        break;
      case "--dsh":
      case "dsh":
        targets.add("dsh");
        break;
      case "--openbitfun":
      case "openbitfun":
        targets.add("openbitfun");
        break;
      case "--user":
        user = true;
        break;
      case "--force":
        force = true;
        break;
      case "--dry-run":
        dryRun = true;
        break;
      case "--upgrade":
        upgrade = true;
        break;
      case "-h":
      case "--help":
        return { help: true };
      default: {
        // The profile name is the one option that takes a value; it is read here
        // so the loop's own `default:` stays the unknown-argument error.
        if (arg !== "--dsh-profile" && !arg.startsWith("--dsh-profile=")) {
          throw new Error(`unknown argument: ${arg}\n\n${HELP}`);
        }
        const inline = arg.split("=", 2)[1];
        const value = inline === undefined ? argv[i + 1] : inline;
        // An empty value is a missing name, whether it was written as
        // `--dsh-profile` or as `--dsh-profile=`.
        if (value === undefined || value === "") throw new Error(`--dsh-profile needs a profile name\n\n${HELP}`);
        // A value that looks like another option is a mistake, not a name: a
        // profile literally called "--force" cannot exist on disk.
        if (/^-/.test(value)) throw new Error(`--dsh-profile needs a profile name, got '${value}'\n\n${HELP}`);
        if (inline === undefined) i++;
        dshProfile = value;
        break;
      }
    }
  }

  if (dshProfile !== undefined && !targets.has("dsh")) {
    throw new Error(`--dsh-profile only applies to the DSH target; add --dsh\n\n${HELP}`);
  }

  if (targets.has("opencode") && targets.has("omos")) {
    throw new Error(`--omos cannot be combined with --opencode; --opencode already installs the omos way when a user-level omos install is detected\n\n${HELP}`);
  }

  if (upgrade && (force || dryRun)) {
    throw new Error(`--upgrade cannot be combined with --force or --dry-run: it reads version stamps and copies nothing\n\n${HELP}`);
  }

  // What the user named, before the default set fills in — --upgrade rebuilds
  // its child command line from this, so a plain --upgrade re-deploys the
  // default set and an explicit target re-deploys exactly that target.
  const explicitTargets = new Set(targets);
  if (targets.size === 0) {
    targets.add("opencode");
    targets.add("claude");
  }
  return { targets, explicitTargets, force, dryRun, user, upgrade, dshProfile };
}

function walk(root, dir, onFile) {
  for (const name of readdirSync(dir)) {
    if (isSkipped(name)) continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(root, full, onFile);
    else onFile(full);
  }
}

/**
 * Copy one file with skip/force/dry-run semantics. displayRoot/displayPrefix
 * only control how the destination is displayed (user-level installs pass the
 * home directory and "~/"); defaults keep the project-relative display.
 */
function copyOne(src, dest, { force, dryRun, displayRoot = process.cwd(), displayPrefix = "" }, counts) {
  const rel = displayPrefix + relative(displayRoot, dest);
  const exists = existsSync(dest);

  if (exists && !force) {
    counts.skipped++;
    console.log(`  skip       ${rel}  (exists, use --force to overwrite)`);
    return;
  }
  if (!dryRun) {
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(src, dest);
  }
  counts[exists ? "overwritten" : "created"]++;
  console.log(`  ${exists ? "overwrite" : "create   "}  ${rel}${dryRun ? "  (dry-run)" : ""}`);
}

/**
 * Write generated content with the same skip/force/dry-run semantics as copyOne.
 * displayRoot/displayPrefix only control how the destination is displayed
 * (the user-level ZCode target passes the home directory and "~/"); defaults
 * keep the project-relative display for all existing callers.
 *
 * `regenerate` marks content the CLI OWNS ENTIRELY and that names the running
 * release: it is written on every run, like the version stamp, because skip-if-
 * exists would freeze the first release that ever deployed it. Only files with no
 * user-editable content may ask for it.
 */
function writeAgent(dest, content, { force, dryRun, regenerate = false, displayRoot = process.cwd(), displayPrefix = "" }, counts) {
  const rel = displayPrefix + relative(displayRoot, dest);
  const exists = existsSync(dest);

  if (exists && !force && !regenerate) {
    counts.skipped++;
    console.log(`  skip       ${rel}  (exists, use --force to overwrite)`);
    return;
  }
  if (!dryRun) {
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, content);
  }
  counts[exists ? "overwritten" : "created"]++;
  const why = dryRun ? "  (dry-run)" : regenerate && exists && !force ? "  (refreshed: rendered from this release)" : "";
  console.log(`  ${exists ? "overwrite" : "create   "}  ${rel}${why}`);
}

/**
 * Stamp the given file with the running package version. Unlike
 * copyOne/writeAgent the stamp is ALWAYS rewritten — it names the version that
 * just deployed these files, so force has no say; dryRun prints the line
 * without writing. displayRoot/displayPrefix only control the label, as there.
 */
function stampVersionFile(dest, { displayRoot = process.cwd(), displayPrefix = "" }, opts) {
  const rel = displayPrefix + relative(displayRoot, dest);
  if (!opts.dryRun) {
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, `${PKG_VERSION}\n`);
  }
  console.log(`  stamp      ${rel}  (${PKG_VERSION})${opts.dryRun ? "  (dry-run)" : ""}`);
}

/**
 * Copy a set's entries under targetRoot/dest. dest is the scope's destination
 * subdirectory: ".opencode"/".claude" at project level, "" at user level
 * (files land directly in the user-level config root).
 */
function copyEntries(set, entries, targetRoot, dest, opts, counts) {
  if (!existsSync(set.from)) {
    console.warn(`warn: source directory for '${set.dest}' is missing in this installation, skipped`);
    return;
  }

  for (const entry of entries) {
    const src = join(set.from, entry);
    if (!existsSync(src)) {
      console.warn(`warn: missing entry '${entry}' in ${set.dest} source, skipped`);
      continue;
    }
    if (statSync(src).isDirectory()) {
      walk(src, src, (fileAbs) =>
        copyOneRendered(set, fileAbs, join(entry, relative(src, fileAbs)), join(targetRoot, dest, entry, relative(src, fileAbs)), opts, counts),
      );
    } else {
      copyOneRendered(set, src, entry, join(targetRoot, dest, entry), opts, counts);
    }
  }
}

/**
 * Copy one asset file. The omos orchestrator append renders its
 * {{disciplines}} marker on every deployment scope — the marker must never
 * ship raw outside this repository's source tree; everything else copies
 * byte-for-byte.
 */
function copyOneRendered(set, src, backendRel, dest, opts, counts) {
  const rel = backendRel.split(sep).join("/");
  if (basename(set.from) === "omos" && rel === "oh-my-opencode-slim/orchestrator_append.md") {
    writeAgent(dest, renderOpencodeAsset("omos", rel, readFileSync(src, "utf8")), opts, counts);
    return;
  }
  copyOne(src, dest, opts, counts);
}

/** True when an omos install already exists at user level (~/.config/opencode). */
function omosUserLevelPresent() {
  const cfgDir = join(homedir(), ".config", "opencode");
  if (existsSync(join(cfgDir, "node_modules", OMOS_PACKAGE))) return true;
  for (const name of ["opencode.json", "opencode.jsonc"]) {
    const file = join(cfgDir, name);
    if (existsSync(file) && readFileSync(file, "utf8").includes(OMOS_PACKAGE)) return true;
  }
  return false;
}

/** True when the OpenCode app is installed (an `opencode` binary on PATH). */
function opencodeInstalled() {
  // A shell only on Windows: npm's shims there are .cmd files, which Node
  // refuses to spawn without one; POSIX keeps the direct spawn.
  const result = spawnSync("opencode", ["--version"], { stdio: "ignore", shell: process.platform === "win32" });
  return !(result.error && result.error.code === "ENOENT");
}

