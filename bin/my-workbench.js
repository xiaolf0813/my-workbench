/**
 * The profile directories this CLI maintains, in the order it reports them.
 *
 * One DSH process composes exactly ONE profile, and `dsh-client-modules` scans
 * only that profile's loader entries — so a settings-page row is per profile,
 * not per DSH home. A DSH home commonly has several: `web` for `dsh web` and
 * `desktop` for DSH Desktop on the machine this was written for. Maintaining
 * only one of them left the other without the page, and no profile NAME is
 * stable enough to hardcode — DSH Desktop picks its own, and a user may have
 * profiles this CLI has never heard of. So every real profile is maintained,
 * and an entry that is not a profile is reported rather than written to.
 *
 * A directory counts as a profile when it carries one of its loader files
 * (`cordis.yml`, the root entry list every profile has; or `cordis.patch.yml`,
 * the user patch layer this CLI writes). A bare directory that has neither is
 * used only when it is the single candidate — the layout of a DSH home that
 * has run once, under any name. `node_modules` is DSH's shared dependency
 * root, never a profile.
 *
 * @param {string} home - the DSH home.
 * @param {string} [only] - maintain exactly this profile instead of every profile found.
 * @returns {{ name: string, dir: string, source: "profile" | "only" | "single" }[]} the profiles to maintain; empty when none applies.
 */
function findProfileDirs(home, only) {
  const profilesDir = join(home, "profiles");
  if (!existsSync(profilesDir)) return [];

  const all = [];
  for (const name of readdirSync(profilesDir).sort()) {
    if (name === PROFILE_LINK_DIR) continue;
    const dir = join(profilesDir, name);
    try {
      if (!statSync(dir).isDirectory()) continue;
    } catch {
      continue; // a broken link or an unreadable entry is not a profile
    }
    all.push(name);
  }
  const initialized = (name) =>
    [PROFILE_ROOT_FILENAME, PROFILE_PATCH_FILENAME, PROFILE_MANIFEST_FILENAME].some((file) => existsSync(join(profilesDir, name, file)));

  // An explicitly named profile is maintained whether or not it looks
  // initialized: the user named it, so the only way to find out is to write.
  if (only !== undefined) {
    return all.includes(only) ? [{ name: only, dir: join(profilesDir, only), source: "only" }] : [];
  }

  const profiles = all
    .filter(initialized)
    .map((name) => ({ name, dir: join(profilesDir, name), source: "profile" }));
  if (profiles.length > 0) return profiles;

  // Nothing initialized: a DSH home with exactly one profile dir is that one
  // profile, which is what a home that has run once looks like.
  if (all.length === 1) return [{ name: all[0], dir: join(profilesDir, all[0]), source: "single" }];
  return [];
}

/** The managed block text for one profile's patch layer. */
function laneUiPatchBlock(rowName) {
  return [
    LANE_UI_BLOCK_BEGIN,
    "# The lane settings page is a PROFILE-layer client plugin: DSH discovers client",
    "# halves by scanning the profile loader's own entries, so a row inside an agent",
    "# preset is never scanned and its page is never served. This single inert row is",
    "# the whole profile-level footprint of the DSH target — no tools, no services,",
    "# and no packages installed. Delete the block to remove the page.",
    "- insert:",
    "    - id: my-workbench-lanes-ui",
    `      name: '${rowName}'`,
    LANE_UI_BLOCK_END,
  ].join("\n");
}

/**
 * Maintain the managed block in one profile's user patch layer: replace it in
 * place when the markers are already there, add it otherwise — as one more item
 * when the file is a plain block sequence, as the whole list when the file is
 * empty, comments only, or a flow empty list (`[]`, the DSH factory default: a
 * top-level array cannot continue with an appended item). Content outside the
 * markers — the user's own rows and comments — is never touched or reordered,
 * and a file of any other shape is left alone for the caller to report:
 * appending there would corrupt it.
 *
 * @returns {"unchanged" | "added" | "updated" | "written-dry" | "skipped"} what happened (or would).
 */
function writeLaneUiPatchRow(profileDir, rowName, opts) {
  const file = join(profileDir, PROFILE_PATCH_FILENAME);
  const block = laneUiPatchBlock(rowName);
  const existing = existsSync(file) ? readFileSync(file, "utf8") : null;
  const begin = existing === null ? -1 : existing.indexOf(LANE_UI_BLOCK_BEGIN);

  let next;
  let outcome;
  if (begin !== -1) {
    const end = existing.indexOf(LANE_UI_BLOCK_END, begin);
    if (end === -1) throw new Error(`${file} has the managed block's opening marker but not its closing marker; fix or delete the block, then re-run`);
    const after = end + LANE_UI_BLOCK_END.length;
    next = existing.slice(0, begin) + block + existing.slice(after);
    outcome = next === existing ? "unchanged" : "updated";
  } else if (existing === null) {
    next = `${block}\n`;
    outcome = "added";
  } else {
    const meaningful = existing
      .split("\n")
      .filter((line) => !/^\s*#/.test(line) && !/^\s*---\s*$/.test(line))
      .join("\n")
      .trim();
    if (meaningful === "[]") {
      const withoutEmptyList = existing
        .split("\n")
        .filter((line) => line.trim() !== "[]")
        .join("\n");
      const separator =
        withoutEmptyList.trim() === "" || withoutEmptyList.endsWith("\n\n") ? "" : withoutEmptyList.endsWith("\n") ? "\n" : "\n\n";
      next = `${withoutEmptyList}${separator}${block}\n`;
      outcome = "added";
    } else if (meaningful === "" || meaningful.startsWith("-")) {
      const separator = existing === "" || existing.endsWith("\n\n") ? "" : existing.endsWith("\n") ? "\n" : "\n\n";
      next = `${existing}${separator}${block}\n`;
      outcome = "added";
    } else {
      outcome = "skipped";
    }
  }

  if (outcome === "unchanged" || outcome === "skipped") return outcome;
  if (opts.dryRun) return "written-dry";
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, next);
  return outcome;
}


