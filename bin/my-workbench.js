/**
 * DSH target: installs ONLY at user level — the agent preset in
 * <DSH_HOME>/.agent-presets/<id>/: preset.yml display metadata, the rendered
 * agent.cordis.yml (orchestrator persona + one row for the lane plugin), and the
 * lane plugin package itself (host half, generated specialist prompts, settings
 * page). Opt-in via --dsh; never touches the project directory, never installs
 * anything into the DSH profile or its node_modules, no downloads. DSH reads a
 * preset when a session mounts it, so a new session picks the change up.
 *
 * The settings page needs one row per PROFILE, because a DSH process composes
 * exactly one profile and scans only that profile's loader entries. `--dsh`
 * therefore maintains the marked block in every profile it finds (`web` for
 * `dsh web`, `desktop` for DSH Desktop, and any other profile present), or in
 * the single profile named by `--dsh-profile`. Destinations are displayed
 * relative to the home directory ("~/") when the DSH home sits inside it.
 */
function applyDsh(opts, counts) {
  const home = dshHome();
  const presetRoot = join(home, ".agent-presets", DSH_PRESET_ID);
  // A relocated DSH home (DSH_HOME outside the user's home) is displayed as the
  // absolute path it is; the default layout displays relative to home.
  const userLevel = insideHome(home);
  const display = userLevel ? { ...opts, displayRoot: homedir(), displayPrefix: "~/" } : opts;
  const shown = userLevel ? `~/${relative(homedir(), presetRoot).split(sep).join("/")}` : presetRoot;
  // Resolve the plugin's two deployment imports BEFORE the first write: a DSH
  // home that cannot supply them must fail with nothing half-installed.
  const specifiers = resolveLaneDependencies(home, DSH_LANE_PLUGIN_DEPS);
  const usedSlots = new Set();
  console.log(`\n${shown}/  (user-level: preset.yml, agent.cordis.yml, lane-plugin/, lane-plugin-ui/)`);
  // Warn before the first write, not after: a profile row written while DSH runs
  // lands on disk but cannot reach the composition the running process already
  // booted, so the symptom is a page that never appears rather than an error.
  const live = dshRunning();
  if (live.running && !opts.dryRun) {
    console.warn("  warn       DSH appears to be running; it refuses profile changes while it is up, and a running process keeps the composition it booted with");
    console.warn(`             matched: ${live.label}`);
    console.warn("             close DSH (and DSH Desktop) first, or reopen it after this run to pick the changes up");
  }
  copyOne(join(PKG_ROOT, "agents", "backends", "dsh", "preset.yml"), join(presetRoot, "preset.yml"), display, counts);
  writeAgent(join(presetRoot, "agent.cordis.yml"), renderDshComposition(usedSlots), display, counts);
  console.log(`  ${DSH_LANE_PLUGIN_DIR}/  (preset-mounted: host half + ${DSH_LANE_KEYS.length} specialist prompts)`);
  installLanePlugin(presetRoot, display, opts, counts, specifiers, usedSlots);
  console.log(`  ${DSH_LANE_UI_DIR}/  (profile-mounted: the settings page)`);
  installLaneUiPlugin(presetRoot, display, opts, counts);
  warnUnusedSlots("dsh", usedSlots);

  // The settings page is a CLIENT plugin, and dsh-client-modules only scans the
  // profile loader's own entries — a row inside an agent preset is never seen.
  // One row per profile is therefore the minimum footprint, and the whole of it.
  const rowName = pathToFileURL(join(presetRoot, DSH_LANE_UI_DIR, "src", "index.js")).href;
  const where = (dir) => (userLevel ? `~/${relative(homedir(), dir).split(sep).join("/")}` : dir);
  const profiles = findProfileDirs(home, opts.dshProfile);

  if (profiles.length === 0) {
    const profilesDir = join(home, "profiles");
    const named =
      opts.dshProfile === undefined ? "no profile directory under" : `--dsh-profile ${opts.dshProfile} names none of`;
    console.log(`  skip       ${named} ${where(profilesDir)}; the settings page was NOT mounted`);
    if (opts.dshProfile === undefined) {
      const present = (existsSync(profilesDir) ? readdirSync(profilesDir) : [])
        .filter((name) => name !== PROFILE_LINK_DIR)
        .sort()
        .join(", ");
      console.log(
        present === ""
          ? `  note       start DSH once so it creates its profile directory, then rerun with --dsh`
          : `  note       entries present: ${present}; none is a profile, so name one explicitly with --dsh-profile <name>`,
      );
    }
    printLaneUiRowFallback(rowName);
  } else {
    for (const profile of profiles) {
      const patchFile = join(profile.dir, PROFILE_PATCH_FILENAME);
      const patchExisted = existsSync(patchFile);
      const outcome = writeLaneUiPatchRow(profile.dir, rowName, opts);
      // A profile chosen by the fallback or by name is not the profile the user
      // is looking at, so which one it is belongs in the line.
      const scope = profile.source === "profile" ? "" : `  (${profile.source === "only" ? "named by --dsh-profile" : "the only profile directory"})`;
      if (outcome === "skipped") {
        console.warn(`  warn       ${where(patchFile)} is not a plain patch list; the managed row was NOT written (appending there would corrupt the file)`);
        printLaneUiRowFallback(rowName);
        continue;
      }
      const label = outcome === "added" && patchExisted ? "append   " : PATCH_LABELS[outcome];
      console.log(`  ${label}  ${where(patchFile)}${scope}${opts.dryRun ? "  (dry-run)" : ""}`);
      console.log(`  note       one inert UI row; no tools, no packages installed`);
      if (outcome === "unchanged") console.log(`  note       the managed block was already current (idempotent)`);
    }
  }
  console.log(`  note       DSH reads presets at session start: open a new session and pick this preset`);
}


// ── Response Convention sync assertion ──────────────────────────────────────

/**
 * The orchestrator's user-facing reply convention is authored twice: in the
 * shared prompt body and again in the omos prompt override. Nothing else
 * keeps the copies in step, so the omos append render asserts they still
 * agree — heading depth, line wrapping and blank-line-only differences are
 * ignored, any other divergence fails the assemble.
 */

/**
 * Whitespace-normalized body of the one `Response Convention` section in one
 * file: everything after the heading until the next ATX heading (or EOF),
 * minus standalone `{{...}}` template placeholder lines, all whitespace
 * collapsed so depth, re-wrapping and blank lines compare equal — except that
 * lines OPENING a list item carry a sentinel, so merging or splitting list
 * items is structural, not formatting, and fails.
 */
function responseConventionBody(rel) {
  const lines = readFileSync(join(PKG_ROOT, rel), "utf8").split("\n");
  const at = [];
  for (let i = 0; i < lines.length; i++) {
    if (/^#{1,6}\s+Response Convention\s*$/.test(lines[i])) at.push(i);
  }
  if (at.length === 0) throw new Error(`${rel} has no 'Response Convention' heading`);
  if (at.length > 1) throw new Error(`${rel} has ${at.length} 'Response Convention' headings; expected exactly one`);
  const body = [];
  for (let i = at[0] + 1; i < lines.length && !/^#{1,6}(\s|$)/.test(lines[i]); i++) body.push(lines[i]);
  const text = body
    .filter((line) => !/^\s*\{\{[\w:-]+\}\}\s*$/.test(line))
    .map((line) => (/^\s*(?:[-*+]|\d+[.)])[ \t]/.test(line) ? `\x00${line}` : line))
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
  if (text === "") throw new Error(`${rel} has an empty 'Response Convention' section`);
  return text;
}

/** Fail the assemble unless both authored copies of the convention agree. */
function assertResponseConventionSync() {
  const prompt = "agents/prompts/orchestrator.md";
  const append = "agents/backends/omos/oh-my-opencode-slim/orchestrator_append.md";
  if (responseConventionBody(prompt) !== responseConventionBody(append)) {
    throw new Error(`'Response Convention' diverges between ${prompt} and ${append} (heading depth, line wrapping and blank lines are ignored); align the two copies`);
  }
}

/**
 * Sync the distributable OpenCode assets from agents/backends/{opencode,omos}/
 * into this repository's live .opencode/ directory (this repo self-hosts omos).
 * In check mode, only reports drift.
 */
function renderOpencodeAsset(backendName, rel, source) {
  const normalized = rel.replaceAll("\\", "/");
  if (backendName !== "omos" || normalized !== "oh-my-opencode-slim/orchestrator_append.md") return source;

  assertResponseConventionSync();

  const marker = "{{disciplines}}";
  if (!source.includes(marker)) {
    throw new Error("agents/backends/omos/oh-my-opencode-slim/orchestrator_append.md must contain {{disciplines}}");
  }
  const disciplines = readFileSync(join(PKG_ROOT, "agents", "disciplines.md"), "utf8").replace(/\s+$/, "");
  return source.replace(marker, disciplines);
}

function syncOpencodeAssets({ check }) {
  const destRoot = join(PKG_ROOT, ".opencode");
  let drifted = 0;

  for (const backendName of ["opencode", "omos"]) {
    const srcRoot = join(PKG_ROOT, "agents", "backends", backendName);
    walk(srcRoot, srcRoot, (fileAbs) => {
      const rel = relative(srcRoot, fileAbs);
      if (rel.startsWith("slots/")) return; // {{slot:...}} texts, not runtime assets
      const dest = join(destRoot, rel);
      const content = renderOpencodeAsset(backendName, rel, readFileSync(fileAbs, "utf8"));
      const current = existsSync(dest) ? readFileSync(dest, "utf8") : null;
      if (current === content) return;
      drifted++;
      if (!check) {
        mkdirSync(dirname(dest), { recursive: true });
        writeFileSync(dest, content);
        console.log(`synced: .opencode/${rel}`);
      } else {
        console.log(`outdated: .opencode/${rel}`);
      }
    });
  }
  return drifted;
}

/**
 * Parse-check one JavaScript artifact with the running Node. Uses `--check`, so
 * nothing is executed and no module is resolved — which is what makes it usable
 * on the lane plugin's host module, whose imports only resolve inside a DSH
 * deployment.
 *
 * stdio is inherited rather than piped: node's own SyntaxError (with its line and
 * column) is then the diagnostic the user reads, and the check acts only on the
 * exit status. Piping would also fail outright in sandboxes that forbid a child
 * process's piped stdio.
 *
 * @returns {string | undefined} a description of the failure, or undefined when the file parses.
 */
function syntaxProblem(file) {
  const result = spawnSync(process.execPath, ["--check", file], { stdio: "inherit" });
  if (result.error !== undefined) return `could not run node --check: ${result.error.message}`;
  if (result.status === 0) return undefined;
  return `node --check failed (exit ${String(result.status)}); the SyntaxError above names the file and position`;
}

/**
 * Validate the generated lane plugin prompt module by importing the rendered
 * bytes from a `data:` URL. Nothing touches the disk, and this checks the exact
 * rendered text rather than a re-render: a bad escape or a duplicate key fails
 * here.
 */
async function lanePromptsProblem(rendered) {
  let mod;
  try {
    mod = await import(`data:text/javascript;base64,${Buffer.from(rendered, "utf8").toString("base64")}`);
  } catch (err) {
    return `the rendered prompt module does not evaluate: ${err.message}`;
  }
  const prompts = mod.LANE_PROMPTS;
  if (prompts === null || typeof prompts !== "object") return "the rendered prompt module exports no LANE_PROMPTS object";
  for (const key of DSH_LANE_KEYS) {
    const value = prompts[key];
    if (typeof value !== "string" || value.trim() === "") return `lane '${key}' has an empty prompt`;
  }
  const extra = Object.keys(prompts).filter((key) => !DSH_LANE_KEYS.includes(key));
  if (extra.length > 0) return `the rendered prompt module carries unknown lane(s): ${extra.join(", ")}`;
  return undefined;
}

/**
 * `my-workbench assemble`: regenerate this repository's generated config from
 * the single-source agents/ tree: `.claude/agents/` (claude backend) and
 * `.opencode/` (opencode + omos backend assets), and render the user-level dsh
 * composition and lane plugin so a broken placeholder fails here. `--check` only
 * verifies.
 */
async function assembleCommand({ check }) {
  const outDir = join(PKG_ROOT, BACKENDS.claude);
  const backend = loadBackend("claude");
  let outdated = 0;
  const usedSlots = new Set();

  for (const problem of agentSourceProblems()) {
    console.log(`${check ? "check FAILED" : "error"}: ${problem}`);
    outdated++;
  }

  for (const name of Object.keys(backend.agents).sort()) {
    const dest = join(outDir, `${name}.md`);
    const content = assembleAgent("claude", name, usedSlots);
    if (check) {
      const current = existsSync(dest) ? readFileSync(dest, "utf8") : null;
      if (current !== content) {
        console.log(`outdated: ${name}.md`);
        outdated++;
      }
    } else {
      mkdirSync(dirname(dest), { recursive: true });
      writeFileSync(dest, content);
      console.log(`assembled: ${name}.md`);
    }
  }
  warnUnusedSlots("claude", usedSlots);

  outdated += syncOpencodeAssets({ check });

  // The stamp names the version that generated these trees; --check compares
  // it too, so a version bump alone still shows up as drift.
  const stamp = join(PKG_ROOT, VERSION_FILE);
  if (check) {
    const current = existsSync(stamp) ? readFileSync(stamp, "utf8") : null;
    if (current !== `${PKG_VERSION}\n`) {
      console.log(`outdated: ${VERSION_FILE}`);
      outdated++;
    }
  } else {
    writeFileSync(stamp, `${PKG_VERSION}\n`);
    console.log(`stamped: ${VERSION_FILE}`);
  }

  // The OpenBitFun agents install at user level, so no generated file lives in
  // this repository to regenerate or compare. Render them anyway: a prompt body
  // this tree no longer has, a roster entry that references it, or an
  // unresolved {{slot:...}} fails here instead of at install time.
  const openbitfunSlots = new Set();
  const openbitfunFailures = [];
  try {
    const openbitfunBackend = loadBackend("openbitfun");
    for (const name of Object.keys(openbitfunBackend.agents).sort()) {
      const rendered = assembleAgent("openbitfun", name, openbitfunSlots);
      if (!check) console.log(`rendered: agents/backends/openbitfun/  ${name}.md (${rendered.length} bytes)`);
    }
    warnUnusedSlots("openbitfun", openbitfunSlots);
  } catch (err) {
    openbitfunFailures.push(err.message);
  }
  if (openbitfunFailures.length > 0) {
    for (const failure of openbitfunFailures) console.log(`${check ? "check FAILED" : "error"}: agents/backends/openbitfun/: ${failure}`);
    outdated += openbitfunFailures.length;
  }

  // The DSH preset and its lane plugin install at user level, so no generated
  // file lives in this repository to regenerate or compare. Render them anyway:
  // an unresolved placeholder or an invalid authored lane fails here instead
  // of at install time or at DSH session start.
  const dshSlots = new Set();
  const dshFailures = [];
  try {
    const rendered = renderDshComposition(dshSlots);
    if (!check) console.log(`rendered: agents/backends/dsh/agent.cordis.yml (${rendered.length} bytes)`);
  } catch (err) {
    dshFailures.push(`agent.cordis.yml: ${err.message}`);
  }
  // Render the lane plugin the way an install would — with the deps left as the
  // bare package names its own peerDependencies declare, so no DSH home is
  // needed. The installed form differs only in those two specifiers. Slot
  // accounting shares `dshSlots` with the composition above: both templates draw
  // on the same backend slot set, and a second set would report dispatch unused.
  // The unused-slot warning therefore waits until after this render — the
  // composition never touches design-skills, only the lane prompts do.
  try {
    const host = renderLaneHost(
      Object.fromEntries(Object.entries(DSH_LANE_PLUGIN_DEPS).map(([alias, pkg]) => [alias, pkg])),
    );
    const roster = laneRosterSource();
    const prompts = renderLanePrompts(dshSlots);
    if (!check) console.log(`rendered: agents/backends/dsh/lane-plugin/ (${host.length + roster.length + prompts.length} bytes)`);
    const promptsProblem = await lanePromptsProblem(prompts);
    if (promptsProblem !== undefined) dshFailures.push(`lane-plugin prompts.generated.js: ${promptsProblem}`);
    for (const problem of lanePluginProblems()) dshFailures.push(`lane-plugin: ${problem}`);
  } catch (err) {
    dshFailures.push(`lane-plugin: ${err.message}`);
  }
  warnUnusedSlots("dsh", dshSlots);
  // The lane settings page is the package that reaches the browser, so it gets
  // the checks whose failure would otherwise only be visible in a running GUI,
  // plus an import of its inert host half (which is what a profile row mounts).
  try {
    for (const problem of laneUiPluginProblems()) dshFailures.push(`lane-plugin-ui: ${problem}`);
    const manifest = laneUiManifest();
    const hostRel = typeof manifest.exports?.["."] === "string" ? manifest.exports["."] : undefined;
    if (hostRel !== undefined) {
      const problem = await laneUiHostProblem(join(DSH_LANE_UI_SRC, hostRel));
      if (problem !== undefined) dshFailures.push(`lane-plugin-ui: ${problem}`);
    }
    if (!check) console.log("rendered: agents/backends/dsh/lane-plugin-ui/ (client roster rendered)");
  } catch (err) {
    dshFailures.push(`lane-plugin-ui: ${err.message}`);
  }
  // Parse-check the authored JavaScript; prompt and roster modules are rendered
  // from JSON and prompt text above. Host dependency placeholders sit in strings.
  for (const file of [
    join(DSH_LANE_PLUGIN_SRC, "host-package", "src", "index.js"),
    join(DSH_LANE_UI_SRC, "src", "index.js"),
    join(DSH_LANE_UI_SRC, "lib", "client.js"),
  ]) {
    if (!existsSync(file)) {
      dshFailures.push(`${relative(PKG_ROOT, file)} is missing`);
      continue;
    }
    const problem = syntaxProblem(file);
    if (problem !== undefined) dshFailures.push(`${relative(PKG_ROOT, file)}: ${problem}`);
  }
  if (dshFailures.length > 0) {
    for (const failure of dshFailures) console.log(`${check ? "check FAILED" : "error"}: agents/backends/dsh/: ${failure}`);
    outdated += dshFailures.length;
  }

  if (check) {
    if (outdated === 0) console.log("check OK: .claude/agents/ and .opencode/ match agents/ source; the dsh composition, lane plugin, lane settings page and openbitfun agents render");
    else {
      console.log(`check FAILED: ${outdated} file(s) outdated or unrenderable; run "my-workbench assemble" to regenerate`);
      process.exitCode = 1;
    }
  }
}

/**
 * Numeric x.y.z compare with prerelease tags ignored ("1.2.3-beta.4" is 1.2.3):
 * negative when `a` is older, 0 when equal, positive when `a` is newer.
 * Unparsable segments count as 0, so junk never looks newer than a real release.
 */
function compareVersions(a, b) {
  const numbers = (v) => String(v).replace(/-.*$/, "").split(".").map((part) => parseInt(part, 10) || 0);
  const left = numbers(a);
  const right = numbers(b);
  for (let i = 0; i < Math.max(left.length, right.length); i++) {
    const diff = (left[i] ?? 0) - (right[i] ?? 0);
    if (diff !== 0) return diff;
  }
  return 0;
}

/**
 * `my-workbench --upgrade`: compare the deployment realm stamps with the npm
 * registry's latest, and auto-upgrade when one is behind: re-run the install
 * as "npx --yes my-workbench@latest [<targets>] [--user] --force" — an upgrade
 * must overwrite the assets it supersedes — then re-read the stamps and verify.
 * main runs it before the prerequisite gates; its only write is that child run.
 */
async function upgradeCommand(opts) {
  const home = homedir();
  // One stamp per deployment realm, at most two: the project root for
  // project-level targets, the home directory for --user and the
  // user-level-only targets (zcode/dsh/openbitfun). A mixed selection checks both.
  const projectTargets = ["opencode", "omos", "claude"].filter((name) => opts.targets.has(name));
  const userLevelOnly = ["zcode", "dsh", "openbitfun"].filter((name) => opts.targets.has(name));
  const roots = [];
  if (projectTargets.length > 0 && !opts.user) {
    roots.push({ file: join(process.cwd(), VERSION_FILE), label: VERSION_FILE, was: null });
  }
  if ((projectTargets.length > 0 && opts.user) || userLevelOnly.length > 0) {
    roots.push({ file: join(home, HOME_VERSION_FILE), label: `~/${HOME_VERSION_FILE}`, was: null });
  }

  // The registry IS the comparison's other half: without it there is nothing
  // to report, so fail fast before reading any stamp.
  const registry = (process.env.npm_config_registry || "https://registry.npmjs.org").replace(/\/+$/, "");
  let latest;
  try {
    const res = await fetch(`${registry}/my-workbench/latest`, { signal: AbortSignal.timeout(5000) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const body = await res.json();
    if (typeof body?.version !== "string" || body.version === "") throw new Error("the response names no version");
    latest = body.version;
  } catch (err) {
    console.error(`error: could not read the latest my-workbench version from ${registry}: ${err?.cause?.code ?? err?.cause?.message ?? err?.message}`);
    process.exitCode = 1;
    return;
  }

  console.log(`my-workbench: comparing deployment stamps with npm latest ${latest}`);
  let found = 0;
  const differing = [];
  let stampDiffersFromCli = false;
  for (const root of roots) {
    if (!existsSync(root.file)) {
      console.log(`  missing    ${root.label}  (not deployed from this CLI version; run the install to stamp it)`);
      continue;
    }
    root.was = readFileSync(root.file, "utf8").trim();
    found++;
    if (root.was === latest) {
      console.log(`  up-to-date ${root.label}  ${root.was}`);
    } else {
      differing.push(root);
      console.log(`  outdated   ${root.label}  ${root.was} -> npm latest ${latest}`);
    }
    if (root.was !== PKG_VERSION) stampDiffersFromCli = true;
  }

  if (found === 0) {
    // Missing stamps alone never trigger the redeploy: there is no deployment
    // to upgrade, only an install the user has not run yet.
    console.log(`  note       run the install first ("npx my-workbench"); --upgrade compares the stamps an install writes`);
    console.log(`done: checked 0 deployment stamp(s) against npm latest ${latest}: none found`);
    process.exitCode = 1;
    return;
  }

  if (differing.length === 0) {
    if (stampDiffersFromCli) console.log(`  note       this CLI is ${PKG_VERSION}; rerun the install to redeploy with it`);
    if (PKG_VERSION !== latest) console.log(`  note       this CLI is ${PKG_VERSION}, npm latest is ${latest}`);
    console.log(`done: checked ${found} deployment stamp(s) against npm latest ${latest}: all match`);
    return;
  }

  // Auto-upgrade unless every differing stamp is numerically NEWER than the
  // registry latest — an unpublished or dev deployment is not behind it.
  const behind = differing.filter((root) => compareVersions(root.was, latest) < 0);
  if (behind.length === 0) {
    console.log(`  note       deployment is newer than npm latest; nothing to upgrade`);
    if (PKG_VERSION !== latest) console.log(`  note       this CLI is ${PKG_VERSION}, npm latest is ${latest}`);
    console.log(`done: checked ${found} deployment stamp(s) against npm latest ${latest}: ${differing.length} differ`);
    process.exitCode = 1;
    return;
  }

  // Rebuild the user's own target selection: explicit flags ride along, a
  // plain --upgrade re-deploys the default set; --force is intentional — an
  // upgrade must overwrite the assets it supersedes.
  const args = ["--yes", `my-workbench@${latest}`];
  for (const name of opts.explicitTargets) args.push(`--${name}`);
  if (opts.user) args.push("--user");
  args.push("--force");
  console.log(`  upgrade    redeploying with npm latest ${latest} via npx (existing files are overwritten)`);
  const child = spawnSync("npx", args, { stdio: "inherit", shell: process.platform === "win32" });
  if (child.error !== undefined) {
    console.error(`error: could not launch npx (${child.error.message}); auto-upgrade needs npm on PATH`);
    process.exitCode = 1;
    return;
  }
  if (child.status !== 0) {
    console.error(`error: the redeploy exited with status ${String(child.status)}; deployments may be inconsistent, rerun "my-workbench --upgrade" after fixing it`);
    process.exitCode = 1;
    return;
  }

  // The child's run rewrites the realm stamps; verify instead of trusting it.
  let allMatch = true;
  for (const root of roots) {
    const deployed = existsSync(root.file) ? readFileSync(root.file, "utf8").trim() : null;
    if (deployed === latest) {
      console.log(root.was === latest ? `  up-to-date ${root.label}  ${deployed}` : `  upgraded   ${root.label}  ${root.was ?? "(was missing)"} -> ${deployed}`);
    } else {
      allMatch = false;
      console.log(deployed === null ? `  missing    ${root.label}  (the redeploy did not stamp it)` : `  outdated   ${root.label}  ${deployed} != npm latest ${latest}`);
    }
  }
  if (!allMatch) {
    console.log(`done: redeployed with npm latest ${latest}, but a checked stamp still differs`);
    process.exitCode = 1;
    return;
  }
  console.log(`done: redeployed with npm latest ${latest}: all checked stamps match`);
}

async function main() {
  let opts;
  try {
    opts = parseArgs(process.argv.slice(2));
  } catch (err) {
    console.error(`error: ${err.message}`);
    process.exitCode = 1;
    return;
  }
  if (opts.help) {
    console.log(HELP);
    return;
  }
  if (opts.command === "assemble") {
    await assembleCommand(opts);
    return;
  }
  // --upgrade installs nothing in this process (a behind stamp is redeployed
  // by the npx child it spawns), so the prerequisite gates below do not apply.
  if (opts.upgrade) {
    await upgradeCommand(opts);
    return;
  }

  // Prerequisite gate: fail fast with no writes. --omos demands an existing
  // user-level omos install because the plugin loads from there — my-workbench
  // never pins a plugin entry and never downloads anything. --dsh demands an
  // existing DSH home, because that is where the preset registry reads presets.
  const prereqFailures = [];
  if (opts.targets.has("opencode") && !opencodeInstalled()) {
    prereqFailures.push("OpenCode is not installed (no 'opencode' on PATH); install OpenCode first");
  }
  if (opts.targets.has("omos")) {
    if (!opencodeInstalled()) prereqFailures.push("OpenCode is not installed (no 'opencode' on PATH); install OpenCode first");
    if (!omosUserLevelPresent()) prereqFailures.push("omos is not installed at user level (~/.config/opencode); install omos first, then rerun with --omos");
  }
  if (opts.targets.has("dsh") && !existsSync(dshHome())) {
    prereqFailures.push(`DSH is not installed (no ${dshHome()}); install DeepSeek Harness first, then rerun with --dsh`);
  }
  if (opts.targets.has("openbitfun") && !existsSync(openbitfunConfigDir())) {
    prereqFailures.push(
      "OpenBitFun is not installed (none of its expected config dirs exists: " +
        "~/.config/openbitfun, ~/Library/Application Support/openbitfun, %APPDATA%\\openbitfun" +
        "); install OpenBitFun first, then rerun with --openbitfun",
    );
  }
  if (prereqFailures.length > 0) {
    for (const failure of prereqFailures) console.error(`error: ${failure}`);
    process.exitCode = 1;
    return;
  }

  const targetRoot = process.cwd();
  // The source-repo guard blocks project-level targets only; --user and
  // --zcode (user level) are safe to run from anywhere, including the source
  // repository itself.
  const touchesProjectTargets = opts.targets.has("opencode") || opts.targets.has("omos") || opts.targets.has("claude");
  if (!opts.user && touchesProjectTargets && resolve(targetRoot) === PKG_ROOT) {
    console.log("current directory is the my-workbench source repository; nothing to copy. Use \"my-workbench assemble\" to regenerate .claude/agents/ from agents/ source.");
    return;
  }

  // Per-target install scope. Project level (default) nests under the current
  // directory; --user installs into each tool's user-level config root instead
  // (OpenCode reads ~/.config/opencode, Claude Code reads ~/.claude). ZCode is
  // always user-level and ignores --user.
  const projectScope = (dest) => ({ root: targetRoot, dest, display: `${dest}/` });
  const scopes = {
    opencode: projectScope(".opencode"),
    omos: projectScope(".opencode"),
    claude: projectScope(".claude"),
  };
  if (opts.user) {
    const userScope = (root, display) => ({ root, dest: "", display });
    scopes.opencode = userScope(join(homedir(), ".config", "opencode"), "~/.config/opencode/");
    scopes.omos = scopes.opencode;
    scopes.claude = userScope(join(homedir(), ".claude"), "~/.claude/");
  }
  // User-level destinations live outside the CWD; display them relative to home.
  const displayOpts = opts.user ? { ...opts, displayRoot: homedir(), displayPrefix: "~/" } : opts;

  const counts = { created: 0, overwritten: 0, skipped: 0 };
  // ZCode and DSH are user-level-only targets with no project footprint; a run
  // that selects only those reports itself as a user-level install.
  const projectTargets = ["opencode", "omos", "claude"].filter((name) => opts.targets.has(name));
  const userLevelLabels = { zcode: "ZCode", dsh: "DSH", openbitfun: "OpenBitFun" };
  const userLevelOnly = Object.keys(userLevelLabels).filter((name) => opts.targets.has(name));
  const dry = opts.dryRun ? "  (dry-run)" : "";
  console.log(
    projectTargets.length === 0
      ? `my-workbench: installing ${userLevelOnly.map((name) => userLevelLabels[name]).join(" + ")} agent setup (user-level)${dry}`
      : opts.user
        ? `my-workbench: installing agent setup at user level (~/.config/opencode, ~/.claude)${dry}`
        : `my-workbench: installing agent setup into ${targetRoot}${dry}`,
  );

  if (opts.targets.has("opencode")) applyOpencode(scopes.opencode, displayOpts, counts);
  if (opts.targets.has("omos")) applyOmos(scopes.omos, displayOpts, counts); // after opencode so core config exists first
  if (opts.targets.has("claude")) {
    console.log(`\n${scopes.claude.display}  (agents/*.md, settings.json)`);
    copyEntries(SETS.claude, SETS.claude.entries, scopes.claude.root, scopes.claude.dest, displayOpts, counts);
    assembleBackend("claude", join(scopes.claude.root, scopes.claude.dest, "agents"), displayOpts, counts);
  }
  if (opts.targets.has("zcode")) applyZcode(opts, counts);
  if (opts.targets.has("dsh")) applyDsh(opts, counts);
  if (opts.targets.has("openbitfun")) applyOpenbitfun(opts, counts);

  // One stamp per deployment realm records what deployed there: the project
  // root for project-level targets, the home directory for --user and the
  // user-level-only targets. A mixed run (e.g. --claude --zcode) stamps both.
  if (projectTargets.length > 0 && !opts.user) stampVersionFile(join(targetRoot, VERSION_FILE), opts, opts);
  if ((projectTargets.length > 0 && opts.user) || userLevelOnly.length > 0) {
    stampVersionFile(join(homedir(), HOME_VERSION_FILE), { ...opts, displayRoot: homedir(), displayPrefix: "~/" }, opts);
  }

  console.log(`\ndone: ${counts.created} created, ${counts.overwritten} overwritten, ${counts.skipped} skipped.`);
  if (counts.created > 0 && !opts.dryRun) {
    // Each target picks its own config up differently; project targets are the
    // only ones with files to commit.
    if (projectTargets.length > 0) {
      console.log(
        opts.user
          ? "next: restart OpenCode / Claude Code so the user-level config is picked up."
          : "next: restart OpenCode / Claude Code so the new config is picked up, then commit the copied files.",
      );
    }
    if (opts.targets.has("zcode")) console.log("next: restart ZCode sessions to pick up the new AGENTS.md and subagents.");
    if (opts.targets.has("dsh")) console.log("next: open a new DSH session and pick the installed preset (DSH reads presets at session start).");
  }
}

main().catch((err) => {
  console.error(`error: ${err?.stack || err}`);
  process.exitCode = 1;
});
